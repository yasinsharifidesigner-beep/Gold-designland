function chips(list) {
  return list.map((text) => ({ text, suggest: text === SUGGEST }));
}

function simple(flow, title, list, extra) {
  return Object.assign({
    flow,
    title,
    confirm: false,
    breakAfter: 0,
    groups: [{ label: '', role: '', chips: chips(list) }]
  }, extra || {});
}

